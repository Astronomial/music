export function youtubePlayerError(code){
  if([101,150].includes(code))return `YouTube отклонил встроенное воспроизведение (код ${code}). Возможны ограничения видео или требование подтвердить аккаунт. Открой трек на YouTube и проверь сообщение там. Вход в Chrome/Edge не переносится в плеер Forma.`;
  if(code===153)return 'YouTube не подтвердил источник встроенного плеера (код 153). Открой трек на YouTube.';
  if(code===100)return 'Видео удалено, закрыто или недоступно (код 100). Проверь его на YouTube.';
  if(code===2)return 'YouTube не принял ссылку на этот трек (код 2). Попробуй выбрать другую версию в поиске.';
  if(code===5)return 'YouTube не смог запустить аудио/видео (код 5). Попробуй повторить запуск или открыть трек в браузере.';
  return 'YouTube не смог воспроизвести трек. Проверь его в браузере и доступность сервиса через текущую сеть/VPN.';
}
