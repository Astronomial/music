const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('forma',{
  desktop:true,
  browserAudio:command=>ipcRenderer.invoke('browser-audio:command',command),
  onBrowserAudio:callback=>{const listener=(_event,state)=>callback(state);ipcRenderer.on('browser-audio:state',listener);return()=>ipcRenderer.removeListener('browser-audio:state',listener);},
  genreMetadata:track=>ipcRenderer.invoke('genre:metadata',track),
  soundAudio:id=>ipcRenderer.invoke('sound:audio',id),
  cancelSound:()=>ipcRenderer.invoke('sound:cancel'),
  syncStatus:()=>ipcRenderer.invoke('sync:status'),
  syncStart:()=>ipcRenderer.invoke('sync:start'),
  syncStop:()=>ipcRenderer.invoke('sync:stop'),
  syncPair:()=>ipcRenderer.invoke('sync:pair'),
  syncForget:()=>ipcRenderer.invoke('sync:forget'),
  syncApprove:id=>ipcRenderer.invoke('sync:approve',id),
  syncReject:id=>ipcRenderer.invoke('sync:reject',id),
  onSync:callback=>{const fn=(_event,value)=>callback(value);ipcRenderer.on('sync:changed',fn);return()=>ipcRenderer.removeListener('sync:changed',fn);},
  load:()=>ipcRenderer.invoke('state:load'),
  save:state=>ipcRenderer.invoke('state:save',state),
  yandexPlaylist:url=>ipcRenderer.invoke('yandex:playlist',url),
  cancelImport:()=>ipcRenderer.invoke('yandex:cancel'),
  catalogRequest:(route,params)=>ipcRenderer.invoke('youtube:request',route,params).then(r=>Object.assign(r.items,{hasMore:r.hasMore})),
  openYouTube:id=>ipcRenderer.invoke('youtube:open',id),
  importLocal:kind=>ipcRenderer.invoke('local:import',kind),
  prepareAudio:ids=>ipcRenderer.invoke('audio:prepare',ids),
  audioError:id=>ipcRenderer.invoke('audio:error',id),
  sources:id=>ipcRenderer.invoke('audio:sources',id),
  downloads:()=>ipcRenderer.invoke('offline:list'),
  removeDownload:id=>ipcRenderer.invoke('offline:remove',id),
  openFolder:()=>ipcRenderer.invoke('folder:open'),
  exportProfile:()=>ipcRenderer.invoke('profile:export'),
  windowControl:action=>ipcRenderer.invoke('window:control',action),
  finishClose:state=>ipcRenderer.invoke('state:close',state),
  onBeforeClose:callback=>{const fn=()=>callback();ipcRenderer.on('app:closing',fn);return ()=>ipcRenderer.removeListener('app:closing',fn);},
  onProgress:callback=> {const fn=(_event,value)=>callback(value);ipcRenderer.on('offline:progress',fn);return ()=>ipcRenderer.removeListener('offline:progress',fn);}
});
